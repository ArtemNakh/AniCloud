ADD FOREIGN KEY(`id`) REFERENCES `user-role`(`userId`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `actors`
ADD FOREIGN KEY(`id`) REFERENCES `films-actors`(`actor_id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `films-actors`
ADD FOREIGN KEY(`film_id`) REFERENCES `films`(`id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `genres`
ADD FOREIGN KEY(`id`) REFERENCES `films-genres`(`genre_id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `films`
ADD FOREIGN KEY(`id`) REFERENCES `films-genres`(`film_id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `roles`
ADD FOREIGN KEY(`id`) REFERENCES `user-role`(`roleId`)
